#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');

const apiKey = process.env.VITE_GIPHY_API_KEY ?? '';
if (!apiKey) {
  console.error('[inject-prod-env] Missing VITE_GIPHY_API_KEY environment variable.');
  console.error('[inject-prod-env] Set it in your CI/CD platform (Vercel, GitHub Actions, etc.)');
  process.exit(1);
}

const outFile = path.resolve(__dirname, '..', 'src', 'environments', 'environment.prod.generated.ts');

const content = `// AUTO-GENERATED by scripts/inject-prod-env.js — DO NOT EDIT
// Source of truth: VITE_GIPHY_API_KEY env var (set in deployment platform).
// This file is gitignored; regenerating it does not change any tracked file.

export const environment = {
  production: true,
  companyName: 'Gifs',
  companyName2: 'App',
  companySlogan: 'Maneja tus gifs',

  giphyApiKey: ${JSON.stringify(apiKey)},
  giphyUrl: 'https://api.giphy.com/v1',
};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, content, 'utf8');
console.log(`[inject-prod-env] Wrote ${path.relative(process.cwd(), outFile)}`);
